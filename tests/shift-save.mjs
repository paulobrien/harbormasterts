import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const dir = await mkdtemp(join(tmpdir(), 'harbor-snapshot-test-'));
try {
  const out = join(dir, 'save.cjs');
  await build({entryPoints:['src/shift-save.ts'], outfile:out, bundle:true, platform:'node', format:'cjs', logLevel:'silent'});
  const {fingerprintLevel, isValidShiftSave, readShiftSave, writeShiftSave, clearShiftSave} = await import(pathToFileURL(out).href);
  const items = new Map();
  const storage = {getItem:k=>items.get(k)??null, setItem:(k,v)=>items.set(k,v), removeItem:k=>items.delete(k)};
  const level = {fingerprint:fingerprintLevel('synthetic'),width:1024,height:768,dockCargoTypes:[0,1]};
  const ship = {id:0,x:10,y:20,angle:0,speed:40,size:0,cargoType:0,cargo:1,state:'sailing',path:[{x:30,y:40}],dockIndex:null,targetDockIndex:0,unloadTime:0,entered:true};
  const snapshot = {version:1,levelFingerprint:level.fingerprint,shiftId:'shift-a',score:5,nextId:1,elapsed:100,spawnIn:4,lastWarning:90,ships:[ship]};
  assert.ok(writeShiftSave(snapshot,level,storage));
  assert.deepEqual(readShiftSave(level,storage),snapshot,'full route and timers round-trip');
  assert.equal(readShiftSave({...level,fingerprint:fingerprintLevel('different')},storage),null,'different map rejected');
  const pressure = {phase:1,phaseElapsed:3,spawnElapsed:2,threshold:.4};
  const activePacing = {from:16,interval:4,maxSmall:999,maxMedium:2,maxLarge:1};
  const pressured = {...snapshot,pressure,activePacing};
  assert.ok(writeShiftSave(pressured,level,storage),'pressure-aware snapshot accepted');
  assert.deepEqual(readShiftSave(level,storage),pressured,'pressure and active stage round-trip');
  assert.equal(isValidShiftSave({...pressured,pressure:{...pressure,phase:4}},level),false,'invalid pressure phase rejected');
  assert.equal(isValidShiftSave({...pressured,pressure:{...pressure,threshold:Infinity}},level),false,'invalid threshold rejected');
  assert.equal(isValidShiftSave({...pressured,activePacing:{...activePacing,interval:0}},level),false,'invalid pacing rejected');
  assert.equal(isValidShiftSave({...snapshot,version:2},level),false,'future schema rejected');
  assert.equal(isValidShiftSave({...snapshot,ships:[ship,ship]},level),false,'duplicate ship ids rejected');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...ship,x:Infinity}]},level),false,'invalid positions rejected');
  const arrival={...ship,x:-10,y:384,path:[],targetDockIndex:null,entered:false,spawnElapsed:1.5};
  assert.equal(isValidShiftSave({...snapshot,ships:[arrival]},level),true,'an incoming boat can be saved');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...arrival,spawnElapsed:2.1}]},level),false,'invalid arrival timers are rejected');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...arrival,entered:true}]},level),false,'an incoming boat cannot already have entered');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...arrival,path:[{x:100,y:100}]}]},level),false,'an incoming boat cannot already have a route');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...ship,dockIndex:99,state:'unloading'}]},level),false,'invalid dock index rejected');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...ship,dockIndex:1,state:'unloading'}]},level),false,'cargo and dock mismatch rejected');
  const mixed={...ship,size:2,cargo:4,cargoType:0,cargoSlots:[0,1,0,1],targetDockIndex:1};
  assert.equal(isValidShiftSave({...snapshot,ships:[mixed]},level),true,'a route can target any matching cargo colour');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...mixed,cargoSlots:[0,1]}]},level),false,'cargo slot count must match the boat size');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...mixed,cargoSlots:[0,1,null,1]}]},level),false,'the cargo count must match occupied slots');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...mixed,cargoSlots:[0,1,0,256]}]},level),false,'invalid slot colours are rejected');
  const partiallyUnloaded={...mixed,cargo:2,cargoSlots:[0,null,0,null],state:'waiting',dockIndex:1,targetDockIndex:null};
  assert.equal(isValidShiftSave({...snapshot,ships:[partiallyUnloaded]},level),true,'a partly unloaded boat can wait at the first berth');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...partiallyUnloaded,dockIndex:0}]},level),false,'a waiting boat cannot still have cargo for its current dock');
  assert.equal(isValidShiftSave({...pressured,activePacing:{...activePacing,allowMultiCargo:'yes'}},level),false,'invalid mixed-cargo pacing is rejected');
  const unloading = {...ship,dockIndex:0,targetDockIndex:null,state:'unloading'};
  assert.equal(isValidShiftSave({...snapshot,nextId:2,ships:[unloading,{...unloading,id:1}]},level),false,'duplicate dock occupants rejected');
  assert.equal(isValidShiftSave({...snapshot,ships:[{...ship,path:[{x:NaN,y:0}]}]},level),false,'invalid route point rejected');
  assert.equal(writeShiftSave(snapshot,level,{setItem(){throw Error('quota')},removeItem(){}}),false,'storage errors are reported');
  clearShiftSave(storage);
  assert.equal(readShiftSave(level,storage),null,'completed or discarded shift clears');
  items.set('harbor-master-saved-shift-v1','{broken');
  assert.equal(readShiftSave(level,storage),null,'corrupt JSON ignored');
  console.log('PASS: shift save round-trip, compatibility, validation, duplicates and storage failures');
} finally { await rm(dir,{recursive:true,force:true}); }
